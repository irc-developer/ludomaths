export type ScenarioKey = keyof typeof strings;
export function s(key: ScenarioKey, locale: 'es' | 'en' = 'es'): string {
  return strings[key][locale === 'en' ? 1 : 0];
}

export function scenarioError(error: unknown): string {
  const message = error instanceof Error ? error.message : '';
  if (message === 'SQUAD_GROUP_COUNTS') return s('squadCountError');
  if (message === 'SQUAD_ALLOCATION_ORDER') return s('squadOrderError');
  if (message === 'SQUAD_COMPLEXITY_LIMIT' || message === 'SQUAD_NUMERICAL_LIMIT') return s('squadLimit');
  if (message === 'SQUAD_OBSERVED_UNSUPPORTED' || message === 'SQUAD_SAVE_REROLL_UNSUPPORTED') return s('squadUnsupported');
  if (message === 'CATALOG_RULES_PENDING') return s('pending');
  if (message.startsWith('CATALOG_')) return s('selectionInvalid');
  if (message.includes('context') || message.startsWith('Heavy')) return s('contextRequired');
  if (message.startsWith('La fiabilidad')) return message;
  return s('invalidInput');
}
